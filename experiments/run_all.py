"""
run_all.py — run all four experiments in sequence.

Features:
  - Experiment-level caching: if all_results.json already has a result for
    an experiment, print "LOADED expN from cache — skipping" and skip rerunning.
  - Trial-level resume: completed_set is populated from trials.jsonl so any
    individual trial that already has a record is skipped automatically.
  - Second model: --second-model flag reruns every experiment with a second
    LLM for cross-model comparison. Results are stored under _model2 keys.
"""

from __future__ import annotations

import json
import sys
import os
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from config import CONFIG
from src.utils.logger import TrialLogger
from src.utils.cost_tracker import COST_TRACKER

from experiments.exp1_static_vs_camouflage_single import run_exp1
from experiments.exp2_single_vs_debate import run_exp2
from experiments.exp3_detection_blind_spot import run_exp3
from experiments.exp4_cheap_fix import run_exp4


def _fmt(val):
    """Format a value for paper_numbers.txt."""
    if isinstance(val, float):
        return f"{val:.4f}"
    return str(val) if val is not None else "N/A"


def generate_paper_numbers(results: dict, output_path: str, config) -> None:
    """
    Write paper_numbers.txt with all key metrics in copy-paste format.

    Args:
        results: Dict mapping experiment name to its result dict.
        output_path: File path to write.
        config: Config object (used for model name labels).
    """
    model1 = config.agent_model
    model2 = config.second_model if config.run_second_model else None

    lines = [
        "=" * 70,
        "PAPER NUMBERS — Blind Spots in the Guard",
        "Generated by run_all.py",
        f"Timestamp: {time.strftime('%Y-%m-%d %H:%M:%S UTC', time.gmtime())}",
        f"Primary model:  {model1}",
        f"Provider:       {config.agent_provider}",
    ]
    if model2:
        lines.append(f"Second model:   {model2} ({config.second_provider})")
    lines += ["=" * 70, ""]

    exp1 = results.get("exp1", {})
    exp2 = results.get("exp2", {})
    exp3 = results.get("exp3", {})
    exp4 = results.get("exp4", {})

    # ---- EXP 1 ----
    lines += [
        f"--- EXP 1: Static vs. Camouflage (Single Agent) [{model1}] ---",
        f"ASR_static:                        {_fmt(exp1.get('asr_static'))}",
        f"ASR_camouflage:                    {_fmt(exp1.get('asr_camouflage'))}",
        f"IDR_static_detector_on_static:     {_fmt(exp1.get('idr_static_on_static'))}",
        f"IDR_static_detector_on_camouflage: {_fmt(exp1.get('idr_static_on_camouflage'))}",
    ]
    cdg = exp1.get("cdg")
    idr_s = exp1.get("idr_static_on_static")
    idr_c = exp1.get("idr_static_on_camouflage")
    if all(isinstance(v, float) for v in [cdg, idr_s, idr_c]):
        lines.append(f"CDG_overall: {cdg:.4f}  (IDR drops from {idr_s:.4f} to {idr_c:.4f})")
    else:
        lines.append("CDG_overall: N/A")
    asr_by_domain = exp1.get("asr_by_domain", {})
    for domain in ["financial", "legal", "general"]:
        lines.append(f"ASR_camouflage_{domain}: {_fmt(asr_by_domain.get(domain))}")
    lines.append("")

    if model2 and "asr_static_model2" in exp1:
        lines += [
            f"--- EXP 1 MODEL 2 [{model2}] ---",
            f"ASR_static_model2:     {_fmt(exp1.get('asr_static_model2'))}",
            f"ASR_camouflage_model2: {_fmt(exp1.get('asr_camouflage_model2'))}",
            f"CDG_overall_model2:    {_fmt(exp1.get('cdg_model2'))}",
            "",
        ]

    # ---- EXP 2 ----
    lines += [
        f"--- EXP 2: Debate Amplification [{model1}] ---",
        f"DAF_camouflage:          {_fmt(exp2.get('daf_camouflage'))}",
        f"DAF_static:              {_fmt(exp2.get('daf_static'))}",
        f"CPS_inject_first (mean): {_fmt(exp2.get('cps_mean'))}",
        "",
    ]
    if model2 and "daf_camouflage_model2" in exp2:
        lines += [
            f"--- EXP 2 MODEL 2 [{model2}] ---",
            f"DAF_camouflage_model2: {_fmt(exp2.get('daf_camouflage_model2'))}",
            f"DAF_static_model2:     {_fmt(exp2.get('daf_static_model2'))}",
            f"CPS_mean_model2:       {_fmt(exp2.get('cps_mean_model2'))}",
            "",
        ]

    # ---- EXP 3 ----
    lines += [f"--- EXP 3: CDG by Domain [{model1}] ---"]
    for domain in ["financial", "legal", "general"]:
        dom_data = exp3.get(domain, {})
        idr_s_d = dom_data.get("idr_static_payload")
        idr_c_d = dom_data.get("idr_camouflage_payload")
        cdg_d = dom_data.get("cdg")
        if all(isinstance(v, float) for v in [idr_s_d, idr_c_d, cdg_d]):
            lines.append(f"CDG_{domain}: {cdg_d:.4f}  "
                         f"(IDR_static={idr_s_d:.4f}, IDR_camouflage={idr_c_d:.4f})")
        else:
            lines.append(f"CDG_{domain}: N/A")
    lines.append("")
    if model2:
        lines += [f"--- EXP 3 MODEL 2 [{model2}] ---"]
        for domain in ["financial", "legal", "general"]:
            dom_data = exp3.get(f"{domain}_model2", {})
            cdg_d = dom_data.get("cdg")
            lines.append(f"CDG_{domain}_model2: {_fmt(cdg_d)}")
        lines.append("")

    # ---- EXP 4 ----
    lines += [f"--- EXP 4: Cheap Fix (Augmented Detector) [{model1}] ---"]
    for domain in ["financial", "legal", "general", "overall"]:
        dom_data = exp4.get(domain, {})
        gb = dom_data.get("gap_before")
        ga = dom_data.get("gap_after")
        imp = dom_data.get("improvement_pct")
        if all(isinstance(v, float) for v in [gb, ga, imp]):
            lines.append(f"CDG_improvement_{domain}: {imp:.1f}%  "
                         f"(gap_before={gb:.4f}, gap_after={ga:.4f})")
        else:
            lines.append(f"CDG_improvement_{domain}: N/A")
    lines.append("")
    if model2:
        lines += [f"--- EXP 4 MODEL 2 [{model2}] ---"]
        for domain in ["financial", "legal", "general", "overall"]:
            dom_data = exp4.get(f"{domain}_model2", {})
            imp = dom_data.get("improvement_pct")
            lines.append(f"CDG_improvement_{domain}_model2: {_fmt(imp)}%")
        lines.append("")

    lines += ["=" * 70, "END OF PAPER NUMBERS", "=" * 70]

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nPaper numbers written to: {output_path}")


def _load_cache(path: str) -> dict:
    """Load all_results.json cache, returning empty dict on any error."""
    if not os.path.exists(path):
        return {}
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, dict) else {}
    except (json.JSONDecodeError, OSError):
        return {}


def _save_cache(cache: dict, path: str) -> None:
    """Persist all_results.json cache after each experiment."""
    with open(path, "w", encoding="utf-8") as f:
        json.dump(cache, f, indent=2, default=str)


def main():
    """Run all experiments sequentially with caching and resume support."""
    import argparse

    parser = argparse.ArgumentParser(description="Run all Chameleon Injection experiments")
    parser.add_argument("--dry-run", action="store_true", default=True,
                        help="Use mock LLM responses (default)")
    parser.add_argument("--no-dry-run", action="store_false", dest="dry_run",
                        help="Use real LLM calls")
    parser.add_argument("--max-tasks", type=int, default=None,
                        help="Limit number of tasks (useful for smoke tests)")
    parser.add_argument("--exp", type=str, default="all",
                        help="Which experiments to run: 1,2,3,4 or 'all'")
    parser.add_argument("--second-model", action="store_true", default=False,
                        help="Also run all experiments with the second model for comparison")
    args = parser.parse_args()

    CONFIG.dry_run = args.dry_run
    CONFIG.run_second_model = args.second_model
    if args.max_tasks:
        CONFIG.max_tasks = args.max_tasks

    print(f"\nCHAMELEON INJECTION EVALUATION FRAMEWORK")
    print(f"Mode:           {'DRY RUN' if CONFIG.dry_run else 'LIVE'}")
    print(f"Primary model:  {CONFIG.agent_provider} / {CONFIG.agent_model}")
    if CONFIG.run_second_model:
        print(f"Second model:   {CONFIG.second_provider} / {CONFIG.second_model}")
    print(f"Results dir:    {CONFIG.results_dir}\n")

    logger = TrialLogger(CONFIG.results_dir)
    all_results_path = os.path.join(CONFIG.results_dir, "all_results.json")

    # Load cache and completed signatures
    cache = _load_cache(all_results_path)
    completed_set = logger.load_completed_signatures()
    print(f"Completed trial signatures loaded: {len(completed_set)}")
    if completed_set:
        print("  (trials already in trials.jsonl will be skipped)")

    results: dict = {}
    exps_to_run = args.exp.split(",") if args.exp != "all" else ["1", "2", "3", "4"]
    t0 = time.time()

    def _maybe_run(exp_num: str, exp_key: str, run_fn, label: str):
        """Run an experiment or load from cache."""
        if exp_num not in exps_to_run:
            return

        print(f"\n{'='*70}")
        print(f"STARTING {label}")
        print(f"{'='*70}")

        cached = cache.get(exp_key)
        if cached and isinstance(cached, dict) and cached:
            print(f"LOADED {exp_key} from cache — skipping")
            results[exp_key] = cached
        else:
            results[exp_key] = run_fn(
                config=CONFIG, logger=logger, completed_set=completed_set
            )
            cache[exp_key] = results[exp_key]
            _save_cache(cache, all_results_path)

        COST_TRACKER.checkpoint(f"After {label}")

    _maybe_run("1", "exp1", run_exp1, "EXPERIMENT 1")
    _maybe_run("2", "exp2", run_exp2, "EXPERIMENT 2")
    _maybe_run("3", "exp3", run_exp3, "EXPERIMENT 3")
    _maybe_run("4", "exp4", run_exp4, "EXPERIMENT 4")

    elapsed = time.time() - t0
    print(f"\nAll experiments completed in {elapsed:.1f}s")
    COST_TRACKER.checkpoint("FINAL")

    paper_numbers_path = os.path.join(CONFIG.results_dir, "paper_numbers.txt")
    generate_paper_numbers(results, paper_numbers_path, CONFIG)

    _save_cache(cache, all_results_path)
    print(f"Full results JSON: {all_results_path}")


if __name__ == "__main__":
    main()
